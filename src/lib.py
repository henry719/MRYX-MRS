# 获取一个数x在一个数组arr中的百分位数
def get_quantile(num, arr):
    arr = np.asarray(arr)
    arr.sort()
    n = len(arr)
    res = 0.0
    if n == 1:
        res = 0.0 if num < arr[0] else 1.0
    elif n > 1:
        l = n - 1
        c = 0.0
        for i in range(n):
            if arr[i] < num:
                c += 1.0
        percent = c / l
        res = 1 if percent > 1 else percent
    return (round(res, 4))


# 处理数组中的离群值
def outlier_box(x):
    arr = np.array(x)
    q1 = np.percentile(arr, 15)
    q3 = np.percentile(arr, 85)
    # q95 = np.percentile(arr, 95)
    q5 = np.percentile(arr, 5)
    iqr = q3 - q1
    minc = q1 - iqr
    maxc = q3 + iqr
    res = []
    for i in range(len(arr)):
        v = arr[i]
        r = 0
        if v < minc:
            r = q5
        elif v > maxc:
            r = maxc
        else:
            r = v
        res.append(r)
    return np.array(res)


# 时序转成星期性因子
def tspweekdic(x):
    x = Series(x)
    index = x.index
    value = x.values
    week = np.array(list(map(lambda x: x.weekday(), index)))
    df = DataFrame({'w': week, 'v': value}, columns=['w', 'v'])
    mean = x.mean()
    wv = (df.groupby(['w'])['v'].mean() / mean).round(2)
    return wv.to_dict()


